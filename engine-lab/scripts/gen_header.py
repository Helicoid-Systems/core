#!/usr/bin/env python3
"""Generate native/hs_native.h from the implemented exports in src/hs_native.rs.

Reproducible header generator for the RD02 laboratory C ABI. Parses every
`#[no_mangle] pub extern "C" fn` in hs_native.rs and emits matching C
prototypes. Status/state macros are taken from the `pub const HS_*` items and
the `SessionState` discriminants in the same file.

Usage:
  python3 scripts/gen_header.py <path/to/src/hs_native.rs> <output/hs_native.h>

The generator is intentionally narrow: it understands only the C ABI subset
used by hs_native.rs. Signatures are then checked by compiling native/harness.c
against the generated header and linking the real cdylib.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

# Rust FFI type -> C type used in the generated header.
TYPE_MAP = {
    "u32": "uint32_t",
    "usize": "size_t",
    "*const c_char": "const char *",
    "*const u8": "const uint8_t *",
    "*mut *const u8": "const uint8_t **",
    "*mut HsEngineCtx": "hs_engine_ctx *",
    "*mut *mut HsEngineCtx": "hs_engine_ctx **",
    "*mut u32": "uint32_t *",
    "()": "void",
}


def parse_exports(src: str) -> list[tuple[str, str, str]]:
    """Return (name, args_c, ret_c) for each no_mangle extern C fn."""
    exports: list[tuple[str, str, str]] = []
    # Match `#[no_mangle]` followed by `pub extern "C" fn name(...) -> T`.
    pattern = re.compile(
        r"#\[no_mangle\]\s*\n\s*pub extern \"C\" fn\s+(\w+)\s*\((.*?)\)\s*(?:->\s*([^{\n]+?))?\s*\{",
        re.S,
    )
    for m in pattern.finditer(src):
        name, args_src, ret_src = m.group(1), m.group(2).strip(), (m.group(3) or "()").strip()
        params: list[str] = []
        if args_src and args_src != "":
            for raw in args_src.split(","):
                raw = raw.strip()
                if not raw:
                    continue
                # `_display: u32` / `ctx: *mut HsEngineCtx` / `out: *mut *mut HsEngineCtx`
                if ":" not in raw:
                    raise SystemExit(f"cannot parse parameter: {raw!r}")
                _, typ = raw.split(":", 1)
                typ = " ".join(typ.strip().split())
                if typ not in TYPE_MAP:
                    raise SystemExit(f"unmapped Rust FFI type {typ!r} in {name}")
                # Keep C parameter names when present for readability.
                pname = raw.split(":", 1)[0].strip().lstrip("_") or "arg"
                params.append(f"{TYPE_MAP[typ]} {pname}")
        ret_src = " ".join(ret_src.split())
        ret = TYPE_MAP.get(ret_src)
        if ret is None:
            raise SystemExit(f"unmapped Rust FFI return type {ret_src!r} in {name}")
        args_c = ", ".join(params) if params else "void"
        exports.append((name, args_c, ret))
    return exports


def parse_consts(src: str) -> list[tuple[str, str]]:
    """Return (name, value) for `pub const HS_*: u32 = N;`."""
    out: list[tuple[str, str]] = []
    for m in re.finditer(r"pub const (HS_\w+):\s*(?:u32|usize)\s*=\s*(\d+);", src):
        out.append((m.group(1), m.group(2)))
    return out


def parse_states(src: str) -> list[tuple[str, str]]:
    """Return (name, value) for SessionState discriminants."""
    out: list[tuple[str, str]] = []
    block = re.search(r"pub enum SessionState\s*\{(.*?)\}", src, re.S)
    if not block:
        raise SystemExit("SessionState enum not found")
    for m in re.finditer(r"(\w+)\s*=\s*(\d+),", block.group(1)):
        out.append((m.group(1), m.group(2)))
    return out


def main() -> int:
    if len(sys.argv) != 3:
        print(__doc__, file=sys.stderr)
        return 2
    src_path = Path(sys.argv[1])
    out_path = Path(sys.argv[2])
    src = src_path.read_text(encoding="utf-8")

    exports = parse_exports(src)
    consts = parse_consts(src)
    states = parse_states(src)
    if not exports:
        raise SystemExit("no exports found")
    if len(exports) != len(re.findall(r"#\[no_mangle\]", src)):
        raise SystemExit("not every no_mangle export could be parsed")

    lines: list[str] = []
    lines.append("/* hs_native.h — Helicoid / RD02 laboratory native bridge seam.")
    lines.append(" *")
    lines.append(" * GENERATED by scripts/gen_header.py from src/hs_native.rs")
    lines.append(" * (implemented #[no_mangle] exports only). Do not hand-edit;")
    lines.append(" * re-run the generator after changing hs_native.rs.")
    lines.append(" *")
    lines.append(" * Scope of this ABI (deliberately narrow):")
    lines.append(" *   - real inert Session<NativeHandler> construct/drop")
    lines.append(" *   - context lifetime: new / prepare / request-close / drain / free")
    lines.append(" *   - bounded validated peer-id input")
    lines.append(" *   - Rust panic containment at the ABI boundary")
    lines.append(" *   - disabled server_keyboard/file/clipboard defaults from real fields")
    lines.append(" *   - connecting / observation exports that return UNAVAILABLE before B03")
    lines.append(" *")
    lines.append(" * This header is NOT a media, grant, input, or control API.")
    lines.append(" * Prepared means inert (real Session owned). It does NOT mean")
    lines.append(" * admitted, connected, or ready-to-view. B03 is not passed.")
    lines.append(" *")
    lines.append(" * Free/call prerequisites (violating them is undefined behaviour;")
    lines.append(" * catch_unwind does NOT catch UB):")
    lines.append(" *   - every ctx must come from hs_engine_ctx_new")
    lines.append(" *   - free exactly once; this ABI does not detect double-free")
    lines.append(" *   - do not use a ctx after hs_engine_ctx_free")
    lines.append(" *   - do not re-enter these functions on the same ctx concurrently")
    lines.append(" */")
    lines.append("#ifndef HS_NATIVE_H")
    lines.append("#define HS_NATIVE_H")
    lines.append("")
    lines.append("#include <stddef.h>")
    lines.append("#include <stdint.h>")
    lines.append("")
    lines.append("#ifdef __cplusplus")
    lines.append('extern "C" {')
    lines.append("#endif")
    lines.append("")
    lines.append("/* --- ABI version --- */")
    for name, val in consts:
        if name == "HS_ABI_VERSION":
            lines.append(f"#define {name} {val}u")
    lines.append("")
    lines.append("/* --- status codes --- */")
    for name, val in consts:
        if name.startswith("HS_STATUS_"):
            lines.append(f"#define {name} {val}u")
    lines.append("")
    lines.append("/* --- context lifecycle states --- */")
    for name, val in states:
        c_name = "HS_STATE_" + name.upper()
        lines.append(f"#define {c_name} {val}u")
    lines.append("")
    lines.append("/* Maximum accepted peer-id length in bytes. */")
    max_peer = dict(consts).get("HS_MAX_PEER_ID_BYTES")
    if max_peer is None:
        raise SystemExit("HS_MAX_PEER_ID_BYTES source constant missing")
    lines.append(f"#define HS_MAX_PEER_ID_BYTES {max_peer}u")
    lines.append("")
    lines.append("/* Opaque context. Construct with hs_engine_ctx_new; free with hs_engine_ctx_free. */")
    lines.append("typedef struct hs_engine_ctx hs_engine_ctx;")
    lines.append("")
    for name, args_c, ret in exports:
        lines.append(f"{ret} {name}({args_c});")
        lines.append("")
    lines.append("#ifdef __cplusplus")
    lines.append("}")
    lines.append("#endif")
    lines.append("")
    lines.append("#endif /* HS_NATIVE_H */")
    lines.append("")

    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {out_path} ({len(exports)} exports)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
